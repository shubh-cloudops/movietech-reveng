"""Export an approved plan to GitHub Issues: one issue per task, one label per milestone.

Uses the GitHub CLI (`gh`), so this code never sees a token: run `gh auth login` once.
Each created issue is recorded in plan/issues.json straight away, so a rerun after an error
skips the tasks that already have an issue instead of creating duplicates.
"""

import json
import subprocess
from pathlib import Path

from movietech.schemas import AcceptancePlan, BuildPlan, Milestone, Task


def body(task: Task, milestone: Milestone, tests: list, issues: dict[str, str]) -> str:
    """The issue text: what to do, how to know it is done, and what it depends on."""

    def ref(task_id: str) -> str:
        url = issues.get(task_id)
        return f"#{url.rsplit('/', 1)[-1]} ({task_id})" if url else task_id

    lines = [task.description, "", f"**Done when:** {task.done_when}",
             f"**Size:** {task.size} · **Milestone:** {milestone.milestone_id} {milestone.title}"]
    if task.depends_on:
        lines.append("**Depends on:** " + ", ".join(ref(t) for t in task.depends_on))
    if task.component_ids:
        lines.append("**Components:** " + ", ".join(task.component_ids))
    if task.paid_resource.strip().lower() != "none":
        lines.append(f"**Paid resource:** {task.paid_resource}")
    if task.files:
        lines += ["", "**Files**"] + [f"- `{f}`" for f in task.files]
    if task.must_haves:
        lines += ["", "**Must-haves delivered**"] + [f"- {m}" for m in task.must_haves]
    covering = [t for t in tests if task.task_id in t.task_ids]
    if covering:
        lines += ["", "**Acceptance tests**"]
        lines += [f"- {t.test_id} ({t.kind}): {t.then}" for t in covering]
    lines += ["", "_Generated by movietech from plan/tasks.json._"]
    return "\n".join(lines)


def export(run_dir: Path, repo: str, run=subprocess.run, dry_run: bool = False) -> list[str]:
    """Create the missing issues in repo (owner/name). Returns the URLs created this time."""
    plan_dir = run_dir / "plan"
    if not (plan_dir / "approval.json").exists():
        raise FileNotFoundError(f"{plan_dir / 'approval.json'} not found. Run approve first.")
    plan = BuildPlan.model_validate_json((plan_dir / "tasks.json").read_text(encoding="utf-8"))
    tests_path = plan_dir / "tests.json"
    tests = (AcceptancePlan.model_validate_json(tests_path.read_text(encoding="utf-8")).tests
             if tests_path.exists() else [])
    record = plan_dir / "issues.json"
    issues = json.loads(record.read_text(encoding="utf-8")) if record.exists() else {}

    def gh(*args: str, stdin: str | None = None) -> str:
        done = run(["gh", *args, "--repo", repo], input=stdin, capture_output=True,
                   text=True, encoding="utf-8", check=True)
        return done.stdout.strip()

    created = []
    for m in plan.milestones:
        if not dry_run:
            gh("label", "create", m.milestone_id, "--description", m.goal[:100], "--force")
        for t in m.tasks:
            if t.task_id in issues:
                continue
            title = f"{t.task_id}: {t.title}"
            if dry_run:
                print(f"would create  {title}  [{m.milestone_id}]")
                continue
            url = gh("issue", "create", "--title", title, "--label", m.milestone_id,
                     "--body-file", "-", stdin=body(t, m, tests, issues)).splitlines()[-1]
            issues[t.task_id] = url
            record.write_text(json.dumps(issues, indent=2), encoding="utf-8")
            created.append(url)
            print(f"{url}  {title}")
    return created
